#!/usr/bin/env python3
"""Regenerate leaderboard/js/bot-stops.mjs: every bot's stop knob and every name
folded into a family, as the board needs them to name a seat.

    uv run python tools/gen_bot_stops.py

Read off the same declarations the menu's slider uses (`ai.aux_spec`,
`ai.aux_names`, `ai.aux_over`) and `ai.LEGACY`, so the board never invents a
stop. Only a knob with named stops is written: a bot with a numeric knob, or
none, is shown by its name alone. `tests/test_leaderboard_sync.py` fails when
the file is stale; the SQL mirror (`sc_bot_profile` in schema.sql) is pinned
there too.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from starconquest import ai, config  # noqa: E402

OUT = ROOT / "leaderboard" / "js" / "bot-stops.mjs"


def knobs() -> dict[str, dict]:
    """{family: {lo, hi, over, names}} for every registered bot with named stops."""
    ai.load_models(ROOT / "models")
    out = {}
    for name in sorted(ai.STRATEGIES):
        names = ai.aux_names(name)
        if names is None:
            continue
        _label, lo, hi, _step, _int = ai.aux_spec(name)
        over = ai.aux_over(name)
        out[name] = {"lo": int(lo), "hi": int(hi), "over": None if over is None else int(over),
                     "names": list(names)}
    return out


def legacy() -> dict[str, dict]:
    """{old: {family, off, on}}: the stop an old name plays at when its own knob
    read off (0) and on (1 or more); one stop for both when it had no knob."""
    out = {}
    for old, (family, stop) in sorted(ai.LEGACY.items()):
        off, on = (stop[min(stop)], stop[max(stop)]) if isinstance(stop, dict) else (stop, stop)
        out[old] = {"family": family, "off": off, "on": on}
    return out


def render() -> str:
    dump = lambda value: json.dumps(value, separators=(",", ":"))  # noqa: E731
    return (
        "// Generated by `uv run python tools/gen_bot_stops.py`: regenerate, don't edit.\n"
        "// Each bot's named stops (ai.aux_spec, ai.aux_names, ai.aux_over) and each name\n"
        "// folded into a family as a stop (ai.LEGACY); sc_bot_profile in schema.sql is the\n"
        "// same table for the database.\n"
        f"export const DEFAULT_STOP = {int(config.AI_AUX)};\n"
        f"export const BOT_KNOBS = {dump(knobs())};\n"
        f"export const BOT_LEGACY = {dump(legacy())};\n"
    )


if __name__ == "__main__":
    OUT.write_text(render())
    print(f"wrote {OUT.relative_to(ROOT)}")
